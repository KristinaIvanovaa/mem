@dp.message(F.sticker | F.photo | F.animation)
async def handle_meme(message: Message):
    if not game["round_active"] or game["game_finished"]:
        return

    if not message.reply_to_message or \
       message.reply_to_message.message_id != game["topic_message_id"]:
        return

    uid = message.from_user.id

    if uid not in game["players"]:
        return await message.reply("Ты не участвуешь в игре.")

    if uid in game["submitted_users"]:
        return await message.reply("Ты уже прислал мем.")

    game["submitted_users"].add(uid)
    game["memes"][message.message_id] = {"user_id": uid, "votes": 0}

    keyboard = InlineKeyboardMarkup(inline_keyboard=[
        [InlineKeyboardButton(text="👍 Голос", callback_data=f"vote:{message.message_id}")]
    ])

    await message.reply("Голосуйте за этот мем!", reply_markup=keyboard)

    if len(game["submitted_users"]) == len(game["players"]):
        await message.answer("Все игроки прислали мемы. Начинается голосование!")


