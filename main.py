@dp.callback_query(F.data == "begin_game")
async def begin_game(callback: CallbackQuery):
    if game["game_finished"]:
        return await callback.answer("Игра завершена.")

    if not game["waiting_players"]:
        return await callback.answer("Игра уже идёт.")

    if len(game["players"]) < 1:
        return await callback.answer("Нужно хотя бы 1 игрок.")

    game["waiting_players"] = False

    text = "👥 *Игроки:*\n"
    for uid, pdata in game["players"].items():
        safe_name = escape_md(pdata["name"])
        text += f"• {safe_name} — 0 баллов\n"

    await callback.message.answer(text, parse_mode="Markdown")

    await start_round(callback.message)


