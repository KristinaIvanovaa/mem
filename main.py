@dp.message()
async def receive_situation(message: Message):
    if not game["waiting_for_situation"]:
        return

    if message.from_user.id != game["situation_author"]:
        return

    situation = message.text
    game["waiting_for_situation"] = False

    game["players"][message.from_user.id]["points"] += 0.5

    await start_custom_round(message.chat, situation)


