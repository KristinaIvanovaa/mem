@dp.callback_query(F.data.startswith("vote:"))
async def vote_callback(callback: CallbackQuery):
    if game["game_finished"]:
        return await callback.answer("Игра завершена.")

    if not game["round_active"]:
        return await callback.answer("Раунд уже завершён.")

    meme_id = int(callback.data.split(":")[1])
    voter_id = callback.from_user.id

    if meme_id not in game["memes"]:
        return await callback.answer("Этот мем уже не участвует.")

    author_id = game["memes"][meme_id]["user_id"]

    if voter_id == author_id:
        return await callback.answer("Нельзя голосовать за свой мем!")

    if voter_id in game["voted_users"]:
        return await callback.answer("Ты уже голосовал!")

    game["memes"][meme_id]["votes"] += 1
    game["players"][author_id]["points"] += 1
    game["voted_users"].add(voter_id)

    await callback.answer("Голос засчитан!")

    if len(game["voted_users"]) == len(game["players"]):
        await finish_round(callback.message)


