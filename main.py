@dp.callback_query(F.data == "join")
async def join_game(callback: CallbackQuery):
    if game["game_finished"]:
        return await callback.answer("Игра завершена.")

    if not game["waiting_players"]:
        return await callback.answer("Набор игроков уже закрыт.")

    user = callback.from_user
    uid = user.id

    if uid not in game["players"]:
        game["players"][uid] = {
            "name": get_display_name(user),
            "points": 0
        }
        await callback.answer("Ты в игре!")
    else:
        return await callback.answer("Ты уже участвуешь.")

    # Обновляем стартовое сообщение
    text = "🎮 *Кто будет играть?*\n\n"
    for uid, pdata in game["players"].items():
        safe_name = escape_md(pdata["name"])
        text += f"• {safe_name}\n"

    keyboard = InlineKeyboardMarkup(inline_keyboard=[
        [InlineKeyboardButton(text="🟢 Я играю!", callback_data="join")],
        [InlineKeyboardButton(text="▶ Начать игру", callback_data="begin_game")]
    ])

    await bot.edit_message_text(
        chat_id=game["start_chat_id"],
        message_id=game["start_message_id"],
        text=text,
        reply_markup=keyboard,
        parse_mode="Markdown"
    )


